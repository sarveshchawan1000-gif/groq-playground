import { ProviderAdapter, ChatRequest, RequestMetrics } from './types';
import { ModelConfig } from '@/config/models';
import { formatSSE, calculateCost } from './sse';

export class MockAdapter implements ProviderAdapter {
  id = 'mock';
  name = 'Simulated Playground Engine (Offline Demo)';

  isConfigured(): boolean {
    return process.env.ENABLE_DEMO_MOCK === 'true';
  }

  getMissingReason(modelConfig: ModelConfig): string {
    return `Simulated mode is disabled. To activate live API responses, add ${modelConfig.requiredEnvVar} in .env.local.`;
  }

  async streamChat(
    request: ChatRequest,
    modelConfig: ModelConfig,
    abortSignal?: AbortSignal
  ): Promise<ReadableStream<Uint8Array>> {
    const startTime = performance.now();
    let ttftMs: number | undefined = undefined;

    const lastMessage = request.messages[request.messages.length - 1];
    const userPrompt = lastMessage?.content || 'Hello';
    const hasImage = Boolean(lastMessage?.attachments && lastMessage.attachments.length > 0);

    let sampleResponse = '';
    if (modelConfig.category === 'reasoning') {
      sampleResponse = `**Reasoning & Execution Trace (${modelConfig.name})**\n\n` +
        `1. **Problem Analysis**: The user requested assistance regarding:\n` +
        `   > "${userPrompt.slice(0, 80)}${userPrompt.length > 80 ? '...' : ''}"\n\n` +
        `2. **Deductive Step**: Examining constraints and parameters...\n` +
        `   - Model Slot: ${modelConfig.slot}\n` +
        `   - Temperature: ${request.settings.temperature}\n` +
        `   - Top-P: ${request.settings.topP}\n\n` +
        `3. **Synthesized Solution**:\n` +
        `\`\`\`typescript\n` +
        `// Clean, modular algorithmic output\n` +
        `export function optimizeWorkflow<T>(items: T[]): T[] {\n` +
        `  return items.filter(Boolean);\n` +
        `}\n` +
        `\`\`\`\n\n` +
        `*Notice: This is a demo response generated by the simulated provider adapter. To execute with live weights, configure ${modelConfig.requiredEnvVar} in your .env.local file.*`;
    } else if (modelConfig.category === 'vision' && hasImage) {
      sampleResponse = `**Multimodal Visual Analysis (${modelConfig.name})**\n\n` +
        `• Detected 1 visual attachment in payload.\n` +
        `• Visual Scene Summary: Image received and processed through the simulated vision pipeline.\n` +
        `• User Query: "${userPrompt}"\n\n` +
        `*To connect this to live vision inference (e.g. Llama 3.2 11B Vision or GPT-4o), configure ${modelConfig.requiredEnvVar} in .env.local.*`;
    } else {
      sampleResponse = `### Response from ${modelConfig.name}\n\n` +
        `Hello! You are testing the **${modelConfig.name}** (${modelConfig.providerModelId}).\n\n` +
        `Here is an answer to your query: *"I have received your prompt and processed it through the playground adapter architecture."*\n\n` +
        `- **Real-time Streaming**: You are observing real-time chunk streaming with sub-millisecond dispatch.\n` +
        `- **Provider Adapter**: Seamlessly swappable with Groq, OpenAI, or Anthropic.\n` +
        `- **Live Keys**: Set \`${modelConfig.requiredEnvVar}\` in your environment to query the real API endpoint.`;
    }

    // Split text into tokens / words for realistic streaming simulation
    const chunks = sampleResponse.match(/.{1,6}/g) || [sampleResponse];

    return new ReadableStream<Uint8Array>({
      async start(controller) {
        try {
          // Simulate initial latency / TTFT
          await new Promise((resolve) => setTimeout(resolve, 80));
          if (abortSignal?.aborted) {
            controller.close();
            return;
          }

          ttftMs = Math.round(performance.now() - startTime);

          for (const chunk of chunks) {
            if (abortSignal?.aborted) {
              controller.close();
              return;
            }
            controller.enqueue(formatSSE('delta', { text: chunk }));
            // Simulate 20ms delay between token packets (~50-100 tokens/s)
            await new Promise((resolve) => setTimeout(resolve, 20));
          }

          const elapsedMs = Math.round(performance.now() - startTime);
          const promptTokens = Math.round(userPrompt.length / 4) + 12;
          const completionTokens = Math.round(sampleResponse.length / 4);
          const totalTokens = promptTokens + completionTokens;
          const tokensPerSecond = elapsedMs > 0 ? Number(((completionTokens / elapsedMs) * 1000).toFixed(1)) : 0;

          const metrics: RequestMetrics = {
            elapsedMs,
            ttftMs,
            promptTokens,
            completionTokens,
            totalTokens,
            tokensPerSecond,
            estimatedCost: calculateCost(promptTokens, completionTokens, modelConfig.pricing),
          };

          controller.enqueue(formatSSE('metrics', { metrics }));
          controller.enqueue(formatSSE('done', {}));
          controller.close();
        } catch (err: unknown) {
          if (abortSignal?.aborted) {
            controller.close();
            return;
          }
          const errorMessage = err instanceof Error ? err.message : 'Unknown simulated error';
          controller.enqueue(formatSSE('error', { error: errorMessage }));
          controller.close();
        }
      },
    });
  }
}
